import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const require = createRequire(import.meta.url), modules = [], ids = new Map();
// A constrained CommonJS packer for Zod's published browser-safe CJS modules.
// No eval, dynamic require, node runtime or third-party CDN in the UI artifact.
function collect(file) {
  if (ids.has(file)) return ids.get(file);
  const id = modules.length; ids.set(file, id); modules.push(null);
  const source = fs.readFileSync(file, 'utf8').replace(/require\(["']([^"']+)["']\)/g, (_all, spec) => {
    if (!spec.startsWith('.')) throw new Error('Unexpected Zod browser dependency: ' + spec);
    return `load(${collect(require.resolve(path.resolve(path.dirname(file), spec)))})`;
  });
  if (/\brequire\s*\(/.test(source)) throw new Error('Unresolved browser require: ' + file);
  modules[id] = `function(module,exports,load){\n${source}\n}`; return id;
}
const root = collect(require.resolve('zod'));
const vendor = `const z = (()=>{const modules=[${modules.join(',\n')}],cache={};function load(id){if(cache[id])return cache[id].exports;const module=cache[id]={exports:{}};modules[id](module,module.exports,load);return module.exports;}return load(${root}).z;})();`;
const contracts = fs.readFileSync('lib/contracts.mjs','utf8').replace("import { z } from 'zod';", '').replace(/export const /g, 'const ');
const panel = fs.readFileSync('client/panel.js', 'utf8');
const license = fs.readFileSync(require.resolve('zod/package.json').replace(/package.json$/, 'LICENSE'),'utf8');
fs.writeFileSync('lib/client.js', `/* Generated by scripts/build-client.mjs. Zod license:\n${license}\n*/\nwindow.__ModuleLoader__.load({id:'dsh-pocket-todo',factory:require=>{\n${vendor}\n${contracts}\n${panel}\n}});\n`);
execFileSync(process.execPath, ['--check', 'lib/client.js'], { stdio: 'inherit' });
console.log('Built native panel, Zod modules:', modules.length);
